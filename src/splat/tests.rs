#[test]
fn spz_every_version_reads_the_same() {
    let all: Vec<Scene> = [MIN_RAW, MIN_V2, MIN_V3, MIN_V4].iter().map(|d| spz::parse(d, Limits::PREVIEW).unwrap()).collect();
    for s in &all {
        assert_eq!((s.total, s.len(), s.sh_degree), (4, 4, 0));
        assert_eq!(s.frame, Frame::RightUpBack);
    }
    assert_eq!(all[0].format, "SPZ v2");
    assert_eq!(all[3].format, "SPZ v4");
    // raw and v2 were written by hand; v3 and v4 by Adobe's SPZ library from the same splats
    // in PLY axes, which it turns to SPZ's (y and z flipped). So pairs match exactly, and
    // across pairs once y and z are flipped back.
    let same = |a: &Scene, b: &Scene, flip: f32| {
        for i in 0..4 {
            let want = [b.pos[i][0], flip * b.pos[i][1], flip * b.pos[i][2]];
            for k in 0..3 {
                assert!((a.pos[i][k] - want[k]).abs() < 1.0 / 128.0, "{} vs {} pos {i}: {:?} vs {:?}", a.format, b.format, a.pos[i], want);
                assert!((a.scale[i][k] - b.scale[i][k]).abs() < 0.07 * b.scale[i][k].max(1e-3), "scale {i}");
            }
            // (The hand-written pair stores colours on a different scale from the spec, so
            // colours are compared within pairs only.)
            if flip > 0.0 {
                assert_eq!(a.color[i], b.color[i], "colour {i}");
            }
            assert!((a.color[i][3] as i32 - b.color[i][3] as i32).abs() <= 1, "opacity {i}");
        }
    };
    same(&all[1], &all[0], 1.0);
    same(&all[3], &all[2], 1.0);
    same(&all[2], &all[0], -1.0);
    // The library-written files decode to the colours they were made from: thirds.
    assert_eq!(all[3].color[0], [85, 85, 128, 230]);
    for i in 0..4 {
        let dot: f32 = (0..4).map(|k| all[3].rot[i][k] * all[2].rot[i][k]).sum();
        assert!(dot.abs() > 0.999, "rotation {i}");
        let dot: f32 = (0..4).map(|k| all[1].rot[i][k] * all[0].rot[i][k]).sum();
        assert!(dot.abs() > 0.999, "rotation {i}");
    }
}

/// A v4 file built here: header, table of contents, zstd streams.
fn spz_v4(points: u32, degree: u8, streams: &[Vec<u8>]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(b"NGSP");
    out.extend_from_slice(&4u32.to_le_bytes());
    out.extend_from_slice(&points.to_le_bytes());
    out.extend_from_slice(&[degree, 12, 0, streams.len() as u8]);
    out.extend_from_slice(&32u32.to_le_bytes());
    out.extend_from_slice(&[0; 12]);
    let comp: Vec<Vec<u8>> = streams.iter().map(|s| ruzstd::encoding::compress_to_vec(&s[..], ruzstd::encoding::CompressionLevel::Fastest)).collect();
    for (c, s) in comp.iter().zip(streams) {
        out.extend_from_slice(&(c.len() as u64).to_le_bytes());
        out.extend_from_slice(&(s.len() as u64).to_le_bytes());
    }
    for c in comp {
        out.extend_from_slice(&c);
    }
    out
}

#[test]
fn spz_v4_with_harmonics() {
    let n = 3usize;
    let streams = vec![vec![0u8; n * 9], vec![255; n], vec![128; n * 3], vec![160; n * 3], vec![0; n * 4], (0..n * 9).map(|i| (128 + i) as u8).collect()];
    let s = spz::parse(&spz_v4(n as u32, 1, &streams), Limits { max_points: 10, keep_sh: true }).unwrap();
    assert_eq!((s.len(), s.sh_degree), (3, 1));
    assert_eq!(s.scale[0], [1.0, 1.0, 1.0]); // 160 / 16 - 10 = 0, exp(0) = 1
    assert_eq!(s.sh[1].to_f32(), 1.0 / 128.0);
    assert_eq!(s.sh.len(), n * 9);
}

#[test]
fn spz_lies_and_damage_are_refused() {
    let n = 3usize;
    let ok = vec![vec![0u8; n * 9], vec![255; n], vec![128; n * 3], vec![160; n * 3], vec![0; n * 4]];
    // More points than a file this size can hold.
    let mut liar = spz_v4(n as u32, 0, &ok);
    liar[8..12].copy_from_slice(&u32::MAX.to_le_bytes());
    assert!(spz::parse(&liar, Limits::PREVIEW).unwrap_err().contains("claims"));
    // A stream shorter than the header says.
    let mut short = ok.clone();
    short[0].truncate(n * 9 - 1);
    assert!(spz::parse(&spz_v4(n as u32, 0, &short), Limits::PREVIEW).is_err());
    // Table of contents pointing past the end.
    let mut cut = spz_v4(n as u32, 0, &ok);
    cut.truncate(cut.len() - 5);
    assert!(spz::parse(&cut, Limits::PREVIEW).is_err());
    // Gzip that ends early.
    assert!(spz::parse(&MIN_V3[..MIN_V3.len() - 10], Limits::PREVIEW).is_err());
    assert!(spz::parse(b"NGSP", Limits::PREVIEW).is_err());
    assert!(spz::parse(b"hello", Limits::PREVIEW).is_err());
    // Bad header numbers.
    let mut deg = spz_v4(n as u32, 0, &ok);
    deg[12] = 9;
    assert!(spz::parse(&deg, Limits::PREVIEW).is_err());
}

#[test]
fn every_truncation_of_a_v4_file_fails_cleanly() {
    let n = 3usize;
    let ok = vec![vec![1u8; n * 9], vec![200; n], vec![100; n * 3], vec![150; n * 3], vec![7; n * 4]];
    let full = spz_v4(n as u32, 0, &ok);
    for len in 0..full.len() {
        let _ = spz::parse(&full[..len], Limits::PREVIEW);
    }
    // And with bytes flipped.
    for i in 0..full.len() {
        let mut d = full.clone();
        d[i] ^= 0x5a;
        let _ = spz::parse(&d, Limits::PREVIEW);
    }
}

#[test]
fn drawing_puts_points_on_the_picture() {
    let s = read(&tmp("draw.ply", &splat_ply(200, 0, None, |i, p| match p {
        "x" => (i % 20) as f32 * 0.1,
        "y" => (i / 20) as f32 * 0.1,
        "opacity" => 4.0,
        "scale_0" | "scale_1" | "scale_2" => -3.0,
        _ => plain(i, p),
    })), Limits::PREVIEW).unwrap();
    let px = s.draw(64, 64, Angle::default(), 1);
    assert_eq!(px.len(), 64 * 64 * 4);
    let covered = px.chunks_exact(4).filter(|p| p[3] > 0).count();
    assert!(covered > 100, "{covered}");
    // Facts for a splat scene.
    assert!(s.facts.iter().any(|(k, _)| *k == "Graphics memory"));
    assert!(s.facts.iter().any(|(k, v)| *k == "Size (main body)" && v.contains("calculated")));
}


/// Real scenes, timed and drawn: `FILESCAPE_SPLAT_SAMPLES=/path/to/folder cargo test --release
/// real_scenes -- --ignored --nocapture`. Pictures go next to them as `<name>.preview.png`.
#[test]
#[ignore]
fn real_scenes() {
    let Ok(dir) = std::env::var("FILESCAPE_SPLAT_SAMPLES") else { return };
    for e in std::fs::read_dir(dir).unwrap().flatten() {
        let p = e.path();
        let n = p.to_string_lossy().to_string();
        if !(n.ends_with(".spz") || n.ends_with(".ply")) {
            continue;
        }
        let t = std::time::Instant::now();
        let s = match read(&p, Limits::PREVIEW) {
            Ok(s) => s,
            Err(e) => {
                eprintln!("{n}: {e}");
                continue;
            }
        };
        let read_time = t.elapsed();
        let t = std::time::Instant::now();
        let px = s.draw(640, 480, Angle::default(), 1);
        let draw_time = t.elapsed();
        image::save_buffer(format!("{n}.preview.png"), &px, 640, 480, image::ExtendedColorType::Rgba8).unwrap();
        eprintln!("{n}: {} splats, read {read_time:?}, drawn {draw_time:?}", s.len());
        for (k, v) in &s.facts {
            eprintln!("    {k}: {v}");
        }
    }
}
