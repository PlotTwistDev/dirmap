#[test]
fn spz_every_version_reads_the_same() {
    let all: Vec<Scene> = [MIN_RAW, MIN_V2, MIN_V3, MIN_V4].iter().map(|d| spz::parse(d, Limits::PREVIEW).unwrap()).collect();
    for s in &all {
        assert_eq!((s.total, s.len(), s.sh_degree), (4, 4, 0));
        assert_eq!(s.frame, Frame::RightUpBack);
    }
    assert_eq!(all[0].format, "SPZ v2");
    assert_eq!(all[3].format, "SPZ v4");
    // raw and v2 were written by hand; v3 and v4 by Adobe's SPZ library from the same splats
    // in PLY axes, which it turns to SPZ's (y and z flipped). So pairs match exactly, and
    // across pairs once y and z are flipped back.
    let same = |a: &Scene, b: &Scene, flip: f32| {
        for i in 0..4 {
            let want = [b.pos[i][0], flip * b.pos[i][1], flip * b.pos[i][2]];
            for k in 0..3 {
                assert!((a.pos[i][k] - want[k]).abs() < 1.0 / 128.0, "{} vs {} pos {i}: {:?} vs {:?}", a.format, b.format, a.pos[i], want);
                assert!((a.scale[i][k] - b.scale[i][k]).abs() < 0.07 * b.scale[i][k].max(1e-3), "scale {i}");
            }
            // (The hand-written pair stores colours on a different scale from the spec, so
            // colours are compared within pairs only.)
            if flip > 0.0 {
                assert_eq!(a.color[i], b.color[i], "colour {i}");
            }
            assert!((a.color[i][3] as i32 - b.color[i][3] as i32).abs() <= 1, "opacity {i}");
        }
    };
    same(&all[1], &all[0], 1.0);
    same(&all[3], &all[2], 1.0);
    same(&all[2], &all[0], -1.0);
    // The library-written files decode to the colours they were made from: thirds.
    assert_eq!(all[3].color[0], [85, 85, 128, 230]);
    for i in 0..4 {
        let dot: f32 = (0..4).map(|k| all[3].rot[i][k] * all[2].rot[i][k]).sum();
        assert!(dot.abs() > 0.999, "rotation {i}");
        let dot: f32 = (0..4).map(|k| all[1].rot[i][k] * all[0].rot[i][k]).sum();
        assert!(dot.abs() > 0.999, "rotation {i}");
    }
}

/// A v4 file built here: header, table of contents, zstd streams.
fn spz_v4(points: u32, degree: u8, streams: &[Vec<u8>]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(b"NGSP");
    out.extend_from_slice(&4u32.to_le_bytes());
    out.extend_from_slice(&points.to_le_bytes());
    out.extend_from_slice(&[degree, 12, 0, streams.len() as u8]);
    out.extend_from_slice(&32u32.to_le_bytes());
    out.extend_from_slice(&[0; 12]);
    let comp: Vec<Vec<u8>> = streams.iter().map(|s| ruzstd::encoding::compress_to_vec(&s[..], ruzstd::encoding::CompressionLevel::Fastest)).collect();
    for (c, s) in comp.iter().zip(streams) {
        out.extend_from_slice(&(c.len() as u64).to_le_bytes());
        out.extend_from_slice(&(s.len() as u64).to_le_bytes());
    }
    for c in comp {
        out.extend_from_slice(&c);
    }
    out
}

