/// Real scenes written out in every S3 format and drawn on the GPU next to the original:
/// `FILESCAPE_SPLAT_SAMPLES=/folder cargo test --release s3_real -- --ignored --nocapture`.
/// Pictures go to `<folder>/s3/`.
#[test]
#[ignore]
fn s3_real_scenes_look_the_same() {
    let Ok(dir) = std::env::var("FILESCAPE_SPLAT_SAMPLES") else { return };
    let out = std::path::Path::new(&dir).join("s3");
    std::fs::create_dir_all(&out).unwrap();
    let limits = Limits { max_points: 1_000_000, keep_sh: false, sh_bytes: Limits::SH_BYTES };
    for e in std::fs::read_dir(&dir).unwrap().flatten() {
        let p = e.path();
        let name = p.file_name().unwrap().to_string_lossy().to_string();
        let Ok(src) = read(&p, limits) else { continue };
        if src.kind != SceneKind::Splat {
            continue;
        }
        // To the trainers' axes (y down, z forward) for the formats that use them, and to
        // glTF's for GLB.
        let flip = |t: T| T { pos: [t.pos[0], -t.pos[1], -t.pos[2]], wxyz: [-t.wxyz[1], t.wxyz[0], -t.wxyz[3], t.wxyz[2]], ..t };
        let ts: Vec<T> = (0..src.len())
            .map(|i| {
                let c = src.color[i];
                let r = src.rot[i];
                T { pos: src.pos[i], scale: src.scale[i], rgb: [c[0], c[1], c[2]].map(|v| v as f32 / 255.0), alpha: c[3] as f32 / 255.0, wxyz: [r[3], r[0], r[1], r[2]] }
            })
            .collect();
        let rdf: Vec<T> = if src.frame == Frame::RightUpBack { ts.iter().map(|&t| flip(t)).collect() } else { ts.clone() };
        let rub: Vec<T> = if src.frame == Frame::RightDownForward { ts.iter().map(|&t| flip(t)).collect() } else { ts.clone() };
        let sog = enc_sog(&rdf);
        let files = [
            ("splat", enc_splat(&rdf)),
            ("compressed.ply", enc_compressed_ply(&rdf)),
            ("sog", sog.clone()),
            ("glb", enc_glb(&rub)),
            ("html", enc_html(&sog, "scene.sog")),
        ];
        let picture = |s: Scene| {
            let id = gpu::want(Arc::new(s), None, View::default(), [480, 320], None);
            gpu::wait_for(id, std::time::Duration::from_secs(120)).expect("GPU picture").rgba
        };
        let base = picture(src);
        image::save_buffer(out.join(format!("{name}.png")), &base, 480, 320, image::ExtendedColorType::Rgba8).unwrap();
        for (ext, data) in files {
            let f = out.join(format!("{name}.{ext}"));
            std::fs::write(&f, &data).unwrap();
            let t = std::time::Instant::now();
            let s = read(&f, limits).unwrap();
            let took = t.elapsed();
            let pic = picture(s);
            let diff = pic.iter().zip(&base).map(|(a, b)| (*a as i32 - *b as i32).abs() as f64).sum::<f64>() / base.len() as f64;
            image::save_buffer(out.join(format!("{name}.{ext}.png")), &pic, 480, 320, image::ExtendedColorType::Rgba8).unwrap();
            eprintln!("{name} as {ext}: {} bytes, read in {took:?}, mean difference {diff:.2} of 255", data.len());
            std::fs::remove_file(&f).ok();
        }
    }
}

