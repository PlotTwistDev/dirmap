#[test]
fn spz_lies_and_damage_are_refused() {
    let n = 3usize;
    let ok = vec![vec![0u8; n * 9], vec![255; n], vec![128; n * 3], vec![160; n * 3], vec![0; n * 4]];
    // More points than a file this size can hold.
    let mut liar = spz_v4(n as u32, 0, &ok);
    liar[8..12].copy_from_slice(&u32::MAX.to_le_bytes());
    assert!(spz::parse(&liar, Limits::PREVIEW).unwrap_err().contains("claims"));
    // A stream shorter than the header says.
    let mut short = ok.clone();
    short[0].truncate(n * 9 - 1);
    assert!(spz::parse(&spz_v4(n as u32, 0, &short), Limits::PREVIEW).is_err());
    // Table of contents pointing past the end.
    let mut cut = spz_v4(n as u32, 0, &ok);
    cut.truncate(cut.len() - 5);
    assert!(spz::parse(&cut, Limits::PREVIEW).is_err());
    // Gzip that ends early.
    assert!(spz::parse(&MIN_V3[..MIN_V3.len() - 10], Limits::PREVIEW).is_err());
    assert!(spz::parse(b"NGSP", Limits::PREVIEW).is_err());
    assert!(spz::parse(b"hello", Limits::PREVIEW).is_err());
    // Bad header numbers.
    let mut deg = spz_v4(n as u32, 0, &ok);
    deg[12] = 9;
    assert!(spz::parse(&deg, Limits::PREVIEW).is_err());
}

