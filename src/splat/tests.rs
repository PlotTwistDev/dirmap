fn tmp(name: &str, data: &[u8]) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("filescape-splat-test-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let p = dir.join(name);
    std::fs::write(&p, data).unwrap();
    p
}

const SPLAT_PROPS: &[&str] = &["x", "y", "z", "nx", "ny", "nz", "f_dc_0", "f_dc_1", "f_dc_2"];

/// A binary 3DGS PLY with `n` splats and `rest` f_rest values per splat, filled by `value`.
fn splat_ply(n: u64, rest: usize, claimed: Option<u64>, value: impl Fn(u64, &str) -> f32) -> Vec<u8> {
    let mut names: Vec<String> = SPLAT_PROPS.iter().map(|s| s.to_string()).collect();
    names.extend((0..rest).map(|i| format!("f_rest_{i}")));
    names.extend(["opacity", "scale_0", "scale_1", "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"].map(String::from));
    let mut out = format!("ply\nformat binary_little_endian 1.0\ncomment Generated by test\nelement vertex {}\n", claimed.unwrap_or(n)).into_bytes();
    for p in &names {
        writeln!(out, "property float {p}").unwrap();
    }
    out.extend_from_slice(b"end_header\n");
    for i in 0..n {
        for p in &names {
            out.extend_from_slice(&value(i, p).to_le_bytes());
        }
    }
    out
}

fn plain(i: u64, p: &str) -> f32 {
    match p {
        "x" => i as f32,
        "y" => 2.0,
        "z" => -1.0,
        "f_dc_0" => 0.0,
        "f_dc_1" => 1.0,
        "f_dc_2" => -1.0,
        "opacity" => 0.0,
        "scale_0" | "scale_1" | "scale_2" => 0.0,
        "rot_0" => 2.0, // w, unnormalised
        "rot_1" | "rot_2" | "rot_3" => 0.0,
        p if p.starts_with("f_rest_") => p[7..].parse::<f32>().unwrap(),
        _ => 0.0,
    }
}

#[test]
fn ply_headers_are_told_apart() {
    let kind = |h: &str| ply::parse_for_test(h.as_bytes()).unwrap();
    assert_eq!(kind("ply\nformat ascii 1.0\nelement vertex 3\nproperty float x\nproperty float y\nproperty float z\nelement face 1\nproperty list uchar int vertex_indices\nend_header\n"), PlyKind::Mesh);
    assert_eq!(kind("ply\nformat binary_little_endian 1.0\nelement vertex 3\nproperty float x\nproperty float y\nproperty float z\nproperty uchar red\nproperty uchar green\nproperty uchar blue\nend_header\n"), PlyKind::PointCloud);
    // A face element with no faces is still a point cloud.
    assert_eq!(kind("ply\nformat ascii 1.0\nelement vertex 3\nproperty float x\nproperty float y\nproperty float z\nelement face 0\nproperty list uchar int vertex_indices\nend_header\n"), PlyKind::PointCloud);
    let splat = String::from_utf8(splat_ply(0, 0, None, plain)).unwrap();
    assert_eq!(kind(&splat), PlyKind::Splat);
    assert_eq!(kind(&splat.replace("property float opacity", "property float trbf_center\nproperty float opacity")), PlyKind::Splat4d);
    assert_eq!(kind("ply\nformat binary_little_endian 1.0\nelement chunk 1\nproperty float min_x\nelement vertex 256\nproperty uint packed_position\nproperty uint packed_rotation\nproperty uint packed_scale\nproperty uint packed_color\nend_header\n"), PlyKind::CompressedSplat);
    assert_eq!(kind("ply\nformat ascii 1.0\nelement camera 1\nproperty float view_px\nend_header\n"), PlyKind::Unknown);
    assert!(ply::parse_for_test(b"not a ply").is_err());
    assert!(ply::parse_for_test(b"ply\nformat ascii 1.0\nelement vertex 1\nproperty float x\n").is_err(), "no end_header");
    assert!(ply::parse_for_test(b"ply\nformat ascii 1.0\nelement vertex -4\nend_header\n").is_err());
}

#[test]
fn splat_ply_values_decode() {
    // Degree 1: 9 f_rest values.
    let p = tmp("decode.ply", &splat_ply(5, 9, None, plain));
    let s = read(&p, Limits { max_points: 100, keep_sh: true, sh_bytes: Limits::SH_BYTES }).unwrap();
    assert_eq!(s.kind, SceneKind::Splat);
    assert_eq!((s.total, s.len(), s.sh_degree), (5, 5, 1));
    assert_eq!(s.pos[3], [3.0, 2.0, -1.0]);
    // sigmoid(0) = 0.5; f_dc 0 → 0.5, 1 → 0.5 + C0, -1 → 0.5 - C0.
    assert_eq!(s.color[0], [128, to_u8(0.5 + SH_C0), to_u8(0.5 - SH_C0), 128]);
    assert_eq!(s.scale[0], [1.0, 1.0, 1.0]);
    // rot_0 is w: normalised and moved last.
    assert_eq!(s.rot[0], [0.0, 0.0, 0.0, 1.0]);
    // PLY keeps red's three, then green's, then blue's; ours is r g b per coefficient.
    let sh: Vec<f32> = s.sh[..9].iter().map(|v| v.to_f32()).collect();
    assert_eq!(sh, vec![0.0, 3.0, 6.0, 1.0, 4.0, 7.0, 2.0, 5.0, 8.0]);
    assert!(s.facts.iter().any(|(k, v)| *k == "Colour" && v.contains("Degree 1")));
    assert!(s.facts.iter().any(|(k, v)| *k == "Made by" && v == "test"));
}

