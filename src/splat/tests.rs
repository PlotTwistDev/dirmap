const MIN_KSPLAT: &[u8] = include_bytes!("testdata/minimal.ksplat");
const MIN_SPLAT: &[u8] = include_bytes!("testdata/minimal.splat");

/// A test splat: position, linear scale, display colour (0–1), linear opacity, rotation w x y z.
#[derive(Clone, Copy)]
struct T {
    pos: [f32; 3],
    scale: [f32; 3],
    rgb: [f32; 3],
    alpha: f32,
    wxyz: [f32; 4],
}

fn test_splats(n: usize) -> Vec<T> {
    (0..n)
        .map(|i| {
            let f = i as f32;
            let q = [1.0 + (f * 0.3).sin(), (f * 0.7).cos(), (f * 1.1).sin() * 0.5, 0.2];
            let l = q.iter().map(|v| v * v).sum::<f32>().sqrt();
            T {
                pos: [(f * 0.37).sin() * 2.0, (f * 0.11).cos() - 0.5, f / n as f32 * 3.0 - 1.5],
                scale: [0.01 + (i % 7) as f32 * 0.005, 0.02, 0.005 + (i % 3) as f32 * 0.01],
                rgb: [(i % 5) as f32 / 4.0 * 0.8 + 0.1, (i % 11) as f32 / 10.0 * 0.8 + 0.1, 0.5],
                alpha: 0.2 + (i % 4) as f32 * 0.2,
                wxyz: q.map(|v| v / l),
            }
        })
        .collect()
}

/// Checks a read scene against the splats it was made from, within quantising tolerances.
fn check_against(s: &Scene, want: &[T], pos_tol: f32, col_tol: u8) {
    assert_eq!((s.len(), s.total, s.bad), (want.len(), want.len(), 0), "{}", s.format);
    for (i, t) in want.iter().enumerate() {
        for k in 0..3 {
            assert!((s.pos[i][k] - t.pos[k]).abs() <= pos_tol, "{} pos {i} {k}: {:?} vs {:?}", s.format, s.pos[i], t.pos);
            let rel = (s.scale[i][k] / t.scale[k]).ln().abs();
            assert!(rel < 0.08, "{} scale {i}: {:?} vs {:?}", s.format, s.scale[i], t.scale);
            assert!((s.color[i][k] as i32 - to_u8(t.rgb[k]) as i32).abs() <= col_tol as i32, "{} colour {i}: {:?} vs {:?}", s.format, s.color[i], t.rgb);
        }
        assert!((s.color[i][3] as i32 - to_u8(t.alpha) as i32).abs() <= 3, "{} alpha {i}", s.format);
        let r = s.rot[i];
        let dot = (r[3] * t.wxyz[0] + r[0] * t.wxyz[1] + r[1] * t.wxyz[2] + r[2] * t.wxyz[3]).abs();
        assert!(dot > 0.995, "{} rotation {i}: {r:?} vs {:?} ({dot})", s.format, t.wxyz);
    }
}

fn enc_splat(ts: &[T]) -> Vec<u8> {
    let mut out = Vec::new();
    for t in ts {
        t.pos.iter().chain(&t.scale).for_each(|v| out.extend(v.to_le_bytes()));
        out.extend(t.rgb.map(to_u8));
        out.push(to_u8(t.alpha));
        out.extend(t.wxyz.map(|v| ((v * 128.0 + 128.0).round()).clamp(0.0, 255.0) as u8));
    }
    out
}

/// PlayCanvas compressed PLY, as `compressed-chunk.ts` packs it (with per-chunk colour).
fn enc_compressed_ply(ts: &[T]) -> Vec<u8> {
    let chunks = ts.len().div_ceil(256);
    let mut h = format!("ply\nformat binary_little_endian 1.0\ncomment Generated by test\nelement chunk {chunks}\n");
    for n in ["min_x", "min_y", "min_z", "max_x", "max_y", "max_z", "min_scale_x", "min_scale_y", "min_scale_z", "max_scale_x", "max_scale_y", "max_scale_z", "min_r", "min_g", "min_b", "max_r", "max_g", "max_b"] {
        h += &format!("property float {n}\n");
    }
    h += &format!("element vertex {}\nproperty uint packed_position\nproperty uint packed_rotation\nproperty uint packed_scale\nproperty uint packed_color\nend_header\n", ts.len());
    let mut out = h.into_bytes();
    let pack = |v: f32, bits: u32| ((v * ((1u32 << bits) - 1) as f32 + 0.5).floor() as u32).min((1 << bits) - 1);
    let norm = |x: f32, lo: f32, hi: f32| if x <= lo { 0.0 } else if x >= hi { 1.0 } else if hi - lo < 1e-5 { 0.0 } else { (x - lo) / (hi - lo) };
    let mut verts = Vec::new();
    for c in ts.chunks(256) {
        let mm = |f: &dyn Fn(&T) -> f32| c.iter().map(f).fold((f32::MAX, f32::MIN), |(a, b), v| (a.min(v), b.max(v)));
        let p = [mm(&|t| t.pos[0]), mm(&|t| t.pos[1]), mm(&|t| t.pos[2])];
        let s = [mm(&|t| t.scale[0].ln()), mm(&|t| t.scale[1].ln()), mm(&|t| t.scale[2].ln())];
        let col = [mm(&|t| t.rgb[0]), mm(&|t| t.rgb[1]), mm(&|t| t.rgb[2])];
        for v in [p[0].0, p[1].0, p[2].0, p[0].1, p[1].1, p[2].1, s[0].0, s[1].0, s[2].0, s[0].1, s[1].1, s[2].1, col[0].0, col[1].0, col[2].0, col[0].1, col[1].1, col[2].1] {
            out.extend(v.to_le_bytes());
        }
        for t in c {
            let p111 = |v: [f32; 3]| pack(v[0], 11) << 21 | pack(v[1], 10) << 11 | pack(v[2], 11);
            let pp = p111([norm(t.pos[0], p[0].0, p[0].1), norm(t.pos[1], p[1].0, p[1].1), norm(t.pos[2], p[2].0, p[2].1)]);
            let ss = p111([norm(t.scale[0].ln(), s[0].0, s[0].1), norm(t.scale[1].ln(), s[1].0, s[1].1), norm(t.scale[2].ln(), s[2].0, s[2].1)]);
            let mut a = t.wxyz;
            let big = (0..4).max_by(|&x, &y| a[x].abs().total_cmp(&a[y].abs())).unwrap();
            if a[big] < 0.0 {
                a = a.map(|v| -v);
            }
            let mut rr = big as u32;
            for (k, v) in a.iter().enumerate() {
                if k != big {
                    rr = rr << 10 | pack(v * std::f32::consts::FRAC_1_SQRT_2 + 0.5, 10);
                }
            }
            let cc = pack(norm(t.rgb[0], col[0].0, col[0].1), 8) << 24 | pack(norm(t.rgb[1], col[1].0, col[1].1), 8) << 16 | pack(norm(t.rgb[2], col[2].0, col[2].1), 8) << 8 | pack(t.alpha, 8);
            for w in [pp, rr, ss, cc] {
                verts.extend(w.to_le_bytes());
            }
        }
    }
    out.extend(verts);
    out
}

fn webp(rgba: &[u8], w: u32, h: u32) -> Vec<u8> {
    let mut out = Vec::new();
    image::codecs::webp::WebPEncoder::new_lossless(&mut out).encode(rgba, w, h, image::ExtendedColorType::Rgba8).unwrap();
    out
}

/// A SOG v2 bundle, laid out as `write-sog.ts` writes one (without harmonics).
fn enc_sog(ts: &[T]) -> Vec<u8> {
    let n = ts.len();
    let w = (n as f32).sqrt().ceil() as u32;
    let h = (n as u32).div_ceil(w);
    let px = (w * h) as usize;
    let log = |v: f32| v.signum() * (v.abs() + 1.0).ln();
    let mut mins = [f32::MAX; 3];
    let mut maxs = [f32::MIN; 3];
    for t in ts {
        for k in 0..3 {
            mins[k] = mins[k].min(log(t.pos[k]));
            maxs[k] = maxs[k].max(log(t.pos[k]));
        }
    }
    let (mut lo, mut hi, mut q, mut sc, mut c0) = (vec![0u8; px * 4], vec![0u8; px * 4], vec![0u8; px * 4], vec![0u8; px * 4], vec![0u8; px * 4]);
    // Codebooks: 256 evenly spaced values over the range used.
    let (smin, smax) = ts.iter().flat_map(|t| t.scale.map(f32::ln)).fold((f32::MAX, f32::MIN), |(a, b), v| (a.min(v), b.max(v)));
    let scale_book: Vec<f32> = (0..256).map(|i| smin + (smax - smin) * i as f32 / 255.0).collect();
    let dc_book: Vec<f32> = (0..256).map(|i| (i as f32 / 255.0 - 0.5) / SH_C0).collect();
    let nearest = |book: &[f32], v: f32| (0..256).min_by(|&a, &b| (book[a] - v).abs().total_cmp(&(book[b] - v).abs())).unwrap() as u8;
    for (i, t) in ts.iter().enumerate() {
        let o = i * 4;
        for k in 0..3 {
            let v = ((log(t.pos[k]) - mins[k]) / (maxs[k] - mins[k]) * 65535.0).round() as u32;
            lo[o + k] = v as u8;
            hi[o + k] = (v >> 8) as u8;
            sc[o + k] = nearest(&scale_book, t.scale[k].ln());
            c0[o + k] = nearest(&dc_book, (t.rgb[k] - 0.5) / SH_C0);
        }
        lo[o + 3] = 255;
        hi[o + 3] = 255;
        sc[o + 3] = 255;
        c0[o + 3] = to_u8(t.alpha);
        let mut a = t.wxyz;
        let big = (0..4).max_by(|&x, &y| a[x].abs().total_cmp(&a[y].abs())).unwrap();
        if a[big] < 0.0 {
            a = a.map(|v| -v);
        }
        let mut k = 0;
        for (j, v) in a.iter().enumerate() {
            if j != big {
                q[o + k] = ((v * std::f32::consts::SQRT_2 * 0.5 + 0.5) * 255.0).round() as u8;
                k += 1;
            }
        }
        q[o + 3] = 252 + big as u8;
    }
    let meta = serde_json::json!({
        "version": 2, "count": n,
        "means": { "mins": mins, "maxs": maxs, "files": ["means_l.webp", "means_u.webp"] },
        "scales": { "codebook": scale_book, "files": ["scales.webp"] },
        "quats": { "files": ["quats.webp"] },
        "sh0": { "codebook": dc_book, "files": ["sh0.webp"] },
    });
    let mut buf = std::io::Cursor::new(Vec::new());
    {
        let mut z = zip::ZipWriter::new(&mut buf);
        let opt = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Stored);
        z.start_file("meta.json", opt).unwrap();
        z.write_all(meta.to_string().as_bytes()).unwrap();
        for (name, data) in [("means_l.webp", &lo), ("means_u.webp", &hi), ("scales.webp", &sc), ("quats.webp", &q), ("sh0.webp", &c0)] {
            z.start_file(name, opt).unwrap();
            z.write_all(&webp(data, w, h)).unwrap();
        }
        z.finish().unwrap();
    }
    buf.into_inner()
}

/// A GLB with `KHR_gaussian_splatting`, floats throughout.
fn enc_glb(ts: &[T]) -> Vec<u8> {
    let n = ts.len();
    let mut bin = Vec::new();
    let mut views = Vec::new();
    let mut accessors = Vec::new();
    let mut add = |vals: Vec<f32>, ty: &str| {
        let at = bin.len();
        vals.iter().for_each(|v| bin.extend(v.to_le_bytes()));
        views.push(serde_json::json!({ "buffer": 0, "byteOffset": at, "byteLength": vals.len() * 4 }));
        accessors.push(serde_json::json!({ "bufferView": views.len() - 1, "componentType": 5126, "count": n, "type": ty }));
        accessors.len() - 1
    };
    let pos = add(ts.iter().flat_map(|t| t.pos).collect(), "VEC3");
    let rot = add(ts.iter().flat_map(|t| [t.wxyz[1], t.wxyz[2], t.wxyz[3], t.wxyz[0]]).collect(), "VEC4");
    let scale = add(ts.iter().flat_map(|t| t.scale).collect(), "VEC3");
    let op = add(ts.iter().map(|t| t.alpha).collect(), "SCALAR");
    let dc = add(ts.iter().flat_map(|t| t.rgb.map(|c| (c - 0.5) / SH_C0)).collect(), "VEC3");
    let json = serde_json::json!({
        "asset": { "version": "2.0", "generator": "test" },
        "extensionsUsed": ["KHR_gaussian_splatting"],
        "buffers": [{ "byteLength": bin.len() }],
        "bufferViews": views, "accessors": accessors,
        "meshes": [{ "primitives": [{ "mode": 0, "attributes": {
            "POSITION": pos, "KHR_gaussian_splatting:ROTATION": rot, "KHR_gaussian_splatting:SCALE": scale,
            "KHR_gaussian_splatting:OPACITY": op, "KHR_gaussian_splatting:SH_DEGREE_0_COEF_0": dc },
            "extensions": { "KHR_gaussian_splatting": { "kernel": "ellipse", "colorSpace": "srgb_rec709_display" } } }] }],
        "nodes": [{ "mesh": 0 }], "scenes": [{ "nodes": [0] }],
    });
    let mut js = json.to_string().into_bytes();
    while js.len() % 4 != 0 {
        js.push(b' ');
    }
    let mut out = Vec::new();
    out.extend(b"glTF");
    out.extend(2u32.to_le_bytes());
    out.extend(((12 + 8 + js.len() + 8 + bin.len()) as u32).to_le_bytes());
    out.extend((js.len() as u32).to_le_bytes());
    out.extend(0x4E4F_534Au32.to_le_bytes());
    out.extend(js);
    out.extend((bin.len() as u32).to_le_bytes());
    out.extend(0x004E_4942u32.to_le_bytes());
    out.extend(bin);
    out
}

/// A SuperSplat-style page with the scene as a base64 `data:` link amid script.
fn enc_html(scene: &[u8], filename: &str) -> Vec<u8> {
    let pad = "// viewer code\n".repeat(2000);
    format!("<!DOCTYPE html><html><head><script>{pad}</script></head><body><script>window.sse={{\"contentUrl\":\"data:application/octet-stream;base64,{}\",\"contentFilename\":\"{filename}\"}};</script></body></html>", data_encoding::BASE64.encode(scene)).into_bytes()
}

